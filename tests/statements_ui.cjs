assert.equal(waterfallTickFormat([{value:2195e8,measure:'absolute'}],1e8),',.0~f');
assert.equal(waterfallTickFormat([{value:100,measure:'absolute'},{value:-250,measure:'relative'}],1e8),',.8~f');
assert.equal(waterfallTickFormat([{value:0,measure:'absolute'}],1e8),',.0~f');
assert.match(cashChangeText(150881601005.77,140837137657.52,'亿元'),/减少 100\.44 亿元（6\.66%）/);

assert.equal(amount({value:50,unit:'%'}),'50.00 %');
assert.equal(esc('<script>"&'), '&lt;script&gt;&quot;&amp;');
assert.match(sourceText({source:'llb',field:'MANANETR',method:'本期累计 − 上季累计',period:'2025-06-30'}),/MANANETR/);
assert.equal(waterfallLabel('其他营业损益（净额）'),'其他营业损益<br>（净额）');
assert.equal(waterfallLabel('期初现金及等价物'),'期初现金及<br>现金等价物');
assert.equal(waterfallLabel('经营净现金流'),'经营活动<br>净现金流');
assert.equal(waterfallLabel('营业总收入'),'营业总收入');
